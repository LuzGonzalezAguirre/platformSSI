CREATE TABLE quality_qwall_lot_setting (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bu_id integer NOT NULL UNIQUE CHECK (bu_id >= 0),
  mode varchar(10) NOT NULL DEFAULT 'GENERAL',
  general_lot_size integer NULL CHECK (general_lot_size >= 0),
  inspection_index varchar(5) NOT NULL DEFAULT '2.5',
  enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE quality_qwall_lot_model_setting (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pn_id integer NOT NULL CHECK (pn_id >= 0),
  lot_size integer NOT NULL CHECK (lot_size >= 0),
  setting_id bigint NOT NULL REFERENCES quality_qwall_lot_setting(id) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT uq_qwall_lot_model UNIQUE (setting_id, pn_id)
);
CREATE INDEX quality_qwall_lot_model_setting_setting_id_idx ON quality_qwall_lot_model_setting(setting_id);
CREATE TABLE quality_qwall_sampling_cell (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_min integer NOT NULL CHECK (lot_min >= 0),
  lot_max integer NULL CHECK (lot_max >= 0),
  inspection_index varchar(5) NOT NULL,
  sample_size integer NULL CHECK (sample_size >= 0),
  CONSTRAINT uq_qwall_sampling_cell UNIQUE (lot_min, inspection_index)
);
